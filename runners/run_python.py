# Python regex corpus runner.
#
# Python is not one regex language. The stdlib `re` module and the third-party
# `regex` module (PyPI, the one the app offers as an alternative engine) accept
# different syntax and sometimes give different answers for the same pattern:
# `regex` adds possessive quantifiers, atomic groups, recursion, variable-width
# lookbehind and set operations that `re` rejects outright.
#
# So which module runs is an ARGUMENT, exactly as `run_r.R` takes `tre` /
# `pcre2` for the same reason:
#
#   python3 run_python.py        -> ground-truth/python.json        (stdlib re)
#   python3 run_python.py re     -> the same, said explicitly
#   python3 run_python.py regex  -> ground-truth/python-regex.json  (PyPI regex)
#
# The default stays `re` so the existing `python` runner config keeps working
# unchanged and `python.json` keeps meaning exactly what it meant before.
#
# stdin:  JSON array of {id, pattern, testText, flags}
# stdout: JSON object of {id: {matches: [{match, index}], error}}
# exit code: 0 on success — per-pattern errors go in the error field. A
#   MISSING ENGINE is not a per-pattern error and exits non-zero instead: a
#   column silently generated by the wrong module would be indistinguishable
#   from a real measurement, which is the failure this corpus exists to avoid.

import json
import sys

engine = sys.argv[1] if len(sys.argv) > 1 else "re"
if engine not in ("re", "regex"):
    sys.stderr.write(f"run_python.py: unknown engine {engine!r} (expected 're' or 'regex')\n")
    sys.exit(2)

if engine == "regex":
    try:
        import regex as engine_mod
    except ImportError:
        sys.stderr.write(
            "run_python.py: the `regex` module is not installed, so this column "
            "cannot be generated. Install it in the runner image (pip install regex) "
            "rather than falling back to `re` — a `re` column labelled `regex` is "
            "worse than no column.\n"
        )
        sys.exit(3)
else:
    import re as engine_mod

entries = json.load(sys.stdin)
results = {}
for e in entries:
    try:
        f = 0
        flags_str = e.get("flags", "")
        if "i" in flags_str:
            f |= engine_mod.IGNORECASE
        if "m" in flags_str:
            f |= engine_mod.MULTILINE
        if "s" in flags_str:
            f |= engine_mod.DOTALL
        if "x" in flags_str:
            f |= engine_mod.VERBOSE
        rx = engine_mod.compile(e["pattern"], f)
        # Always emit all matches regardless of 'g' flag — see docs/v1-corpus-fix-spec.md
        # and matches the bridge's behavior.
        matches = [
            {"match": m.group(), "index": m.start()}
            for m in rx.finditer(e["testText"])
        ]
        results[e["id"]] = {"matches": matches, "error": None}
    except Exception as ex:
        results[e["id"]] = {"matches": [], "error": str(ex)}
json.dump(results, sys.stdout)
